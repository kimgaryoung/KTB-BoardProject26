async (page) => {
    await page.unroute('**/server-api/v1/**');
    page.setDefaultTimeout(7000);
    const base = 'http://localhost:8080';
    const project = '/Users/garyeong/IdeaProjects/KTB-BoardProject26';
    const login = await page.request.post(`${base}/server-api/v1/auth/login`, { data: { email: 'community-demo@example.test', password: 'DemoCommunity1!' } });
    if (!login.ok()) throw new Error('Demo login failed');
    const assert = (condition, message) => { if (!condition) throw new Error(message); };
    const uploadedImageVisible = async locator => {
        await locator.waitFor();
        await locator.evaluate(image => image.decode());
        assert(await locator.evaluate(image => image.naturalWidth > 0), 'image must actually decode');
    };
    await page.goto(`${base}/community/1`);
    await page.getByRole('link', { name: '글 작성', exact: true }).click();
    await page.locator('#title').fill('사진 첨부 동작 테스트');
    await page.locator('#content').fill('사진이 글 본문과 커뮤니티 목록에 표시됩니다.');
    await page.locator('#image').setInputFiles(`${project}/frontend/public/background/img_2.png`);
    await uploadedImageVisible(page.locator('#imagePreview'));
    await page.getByRole('button', { name: '완료', exact: true }).click();
    await page.waitForURL('**/post/*');
    const postUrl = page.url();
    const postId = postUrl.split('/').pop();
    await uploadedImageVisible(page.locator('.contentImg img'));
    const firstUrl = await page.locator('.contentImg img').getAttribute('src');
    await page.locator('#communityLink').click();
    const card = page.locator(`.boardList > a[href="/post/${postId}"]`);
    await uploadedImageVisible(card.locator('.postThumbnail'));
    await page.getByRole('searchbox', { name: '이 커뮤니티의 게시글 검색', exact: true }).fill('사진 첨부 동작');
    await page.getByRole('button', { name: '글 검색', exact: true }).click();
    await uploadedImageVisible(page.locator(`.boardList > a[href="/post/${postId}"] .postThumbnail`));
    await page.goto(postUrl);
    await page.getByRole('button', { name: '수정', exact: true }).click();
    await uploadedImageVisible(page.locator('#imagePreview'));
    await page.locator('#image').setInputFiles({ name: 'fake.png', mimeType: 'image/png', buffer: Buffer.from('not an image') });
    await page.locator('#imageError').filter({ hasText: /이미지|사진/ }).waitFor();
    assert(await page.locator('#imagePreview').getAttribute('src') === firstUrl, 'invalid selection must preserve old preview');
    await page.locator('#image').setInputFiles(`${project}/frontend/public/background/img_1.jpg`);
    await page.waitForFunction(() => !document.querySelector('#submit').disabled && document.querySelector('#imagePreview').src.startsWith('blob:'));
    await uploadedImageVisible(page.locator('#imagePreview'));
    await page.getByRole('button', { name: '수정하기', exact: true }).click();
    await page.waitForURL('**/post/*');
    await uploadedImageVisible(page.locator('.contentImg img'));
    const replacementUrl = await page.locator('.contentImg img').getAttribute('src');
    assert(replacementUrl !== firstUrl, 'replacement must persist a new image');
    await page.getByRole('button', { name: '수정', exact: true }).click();
    await uploadedImageVisible(page.locator('#imagePreview'));
    await page.getByRole('button', { name: '사진 삭제', exact: true }).click();
    await page.getByRole('button', { name: '수정하기', exact: true }).click();
    await page.waitForURL('**/post/*');
    await page.getByRole('heading', { name: '사진 첨부 동작 테스트', exact: true }).waitFor();
    assert(await page.locator('.contentImg img').count() === 0, 'removed photo must disappear from body');
    await page.locator('#communityLink').click();
    await page.locator(`.boardList > a[href="/post/${postId}"]`).waitFor();
    assert(await page.locator(`.boardList > a[href="/post/${postId}"] .postThumbnail`).count() === 0, 'removed photo must disappear from list');
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile cards must fit');
    return { postId, passed: ['editor preview', 'actual multipart upload', 'body image', 'list and search thumbnail', 'invalid replacement preserves previous photo', 'replace', 'remove', 'mobile width'] };
}
